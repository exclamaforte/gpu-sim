#!/usr/bin/env python3
"""Generate the pass-through half of the virtual-device libcuda shim.

The measurement that shapes this file (gpu-sim-7q3w.4, probe_capacity.py):
`libtorch_cuda.so` has ZERO undefined cu*/cuda* symbols -- torch resolves the driver
through cuGetProcAddress, not through the dynamic linker. But libcudart and a few
direct dlsym callers still ask for names, so a shim that only defines the functions it
OVERRIDES would turn every other driver call into "undefined symbol".

So: every cu* symbol the real driver exports gets a 4-instruction trampoline that jumps
through a pointer the constructor fills from the real driver. Arguments are untouched
(System V: a tail `jmp` preserves every register), so this is a pass-through for ~700
entry points with no hand-written signature anywhere -- and therefore no chance of a
wrong prototype silently corrupting a call.

Outputs (written next to this script, into the build dir given as argv[1]):
  forwarders.S   one trampoline per forwarded symbol
  forwarders.c   the constructor that resolves them
"""
import re
import subprocess
import sys

REAL = "/usr/lib/libcuda.so.1"

# Functions vdev.c implements itself; the generator must not also emit them.
OVERRIDES = {
    "cuInit", "cuDeviceGetCount", "cuDeviceGet", "cuDeviceGetName",
    "cuDeviceGetUuid", "cuDeviceGetPCIBusId", "cuDeviceGetAttribute",
    "cuDeviceTotalMem_v2", "cuDeviceTotalMem", "cuMemGetInfo_v2", "cuMemGetInfo",
    "cuDevicePrimaryCtxRetain", "cuDevicePrimaryCtxRelease_v2",
    "cuDevicePrimaryCtxRelease", "cuDevicePrimaryCtxGetState",
    "cuDevicePrimaryCtxSetFlags_v2", "cuCtxCreate_v2", "cuCtxCreate",
    "cuGetProcAddress", "cuGetProcAddress_v2", "cuGetProcAddress_v2_ptsz",
    "cuGetProcAddress_ptsz", "cuDriverGetVersion",
}
# Internal dispatcher entry points that must NOT be exported: libnvidia-ml looks
# cuGetExportTable up in the GLOBAL scope, finds our trampoline instead of the real
# driver, and the real function then crashes -- measured (SIGSEGV inside nvmlInit,
# gdb bt: fwd_cuGetExportTable <- libnvidia-ml). Not exporting it lets NVML's lookup
# fail cleanly, which it already handles.
DENY = {"cuGetExportTable"}

PINNED = re.compile(r"^(cu|nvrtc)[A-Za-z0-9_]*$")


def symbols(path=REAL):
    out = subprocess.run(["nm", "-D", "--defined-only", path],
                         check=True, capture_output=True, text=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] == "T" and PINNED.match(parts[2]):
            names.append(parts[2])
    return sorted(set(names) - OVERRIDES - DENY)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    names = symbols()
    with open(f"{out}/forwarders.S", "w") as f:
        f.write("/* generated by gen_forwarders.py -- do not edit */\n\t.text\n")
        for n in names:
            # A missing pointer must RETURN CUDA_ERROR_NOT_SUPPORTED, never jump to 0:
            # libnvidia-ml looks cuGetExportTable up in the global scope, finds this
            # trampoline, and a NULL jump there is a SIGSEGV inside nvmlInit.
            f.write(f"\t.globl {n}\n\t.type {n}, @function\n{n}:\n"
                    # GOTPCREL gives the ADDRESS OF THE VARIABLE; the function
                    # pointer is its CONTENTS. The first version omitted the
                    # load and jumped into .data: SEGV_ACCERR the first time a
                    # forwarded symbol was called (core 4023312, reproduced
                    # from probe_vdev.py, 2026-11-22).
                    f"\tmovq fwd_{n}@GOTPCREL(%rip), %rax\n\tmovq (%rax), %rax\n"
                    f"\ttestq %rax, %rax\n"
                    f"\tje 1f\n\tjmp *%rax\n1:\tmovl $801, %eax\n\tret\n"
                    f"\t.size {n}, .-{n}\n")
    with open(f"{out}/forwarders.c", "w") as f:
        f.write('/* generated by gen_forwarders.py -- do not edit */\n'
                '#define _GNU_SOURCE\n#include <dlfcn.h>\n#include <link.h>\n#include <stdio.h>\n'
                '#include <stdlib.h>\nvoid *fwd_real_handle;\n')
        for n in names:
            f.write(f"void *fwd_{n};\n")
        f.write('\n__attribute__((constructor)) static void fwd_init(void) {\n'
                '    const char *p = getenv("VDEV_REAL_CUDA");\n'
                '    /* Plain dlopen, RTLD_LOCAL: our own file carries DT_SONAME\n'
                '     * libcuda-vdev.so.1, so this resolves to the REAL driver and not to us\n'
                '     * (that collision was measured as infinite cuInit recursion). dlmopen into\n'
                '     * a new namespace is NOT an option: the NVIDIA driver crashes in its own\n'
                '     * mutex there. */\n'
                '    fwd_real_handle = dlopen(p ? p : "' + REAL + '", RTLD_NOW | RTLD_LOCAL);\n'
                '    if (!fwd_real_handle) { fprintf(stderr, "vdev: cannot load real driver: %s\\n", dlerror()); abort(); }\n')
        for n in names:
            f.write(f'    fwd_{n} = dlsym(fwd_real_handle, "{n}");\n')
        f.write("}\n")
    print(f"{len(names)} forwarded + {len(OVERRIDES)} overridden")


if __name__ == "__main__":
    main()
