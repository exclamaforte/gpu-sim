#!/usr/bin/env python3
"""Generate the pass-through half of the virtual NVML shim (gpu-sim-7q3w.4 D2/A1).

Same construction as shim/gen_forwarders.py, for the same reason: the real
libnvidia-ml.so.1 exports 400+ entry points and a hand-written prototype for any
of them is a silent-corruption risk.  Every nvml* symbol the real library exports
gets a trampoline that loads the real function pointer from a constructor-filled
slot; the functions nvml.c overrides are excluded, so the illusion is the small
named set and everything else is the real library.

The trampoline MUST dereference the slot: @GOTPCREL gives the address of the
pointer variable, not the function pointer.  That omission was a real SIGSEGV
(core 4023312) in the driver shim; see gen_forwarders.py.

    python3 shim/gen_nvml_forwarders.py <build-dir>
"""
import re
import subprocess
import sys

REAL = "/usr/lib/libnvidia-ml.so.1"

# Implemented in nvml.c (the modelled identity + the calls torch/A1 needs).
OVERRIDES = {
    "nvmlInit", "nvmlInit_v2", "nvmlShutdown", "nvmlErrorString",
    "nvmlSystemGetDriverVersion", "nvmlSystemGetConfComputeSettings",
    "nvmlSystemGetConfComputeState",
    "nvmlDeviceGetCount", "nvmlDeviceGetCount_v2",
    "nvmlDeviceGetHandleByIndex", "nvmlDeviceGetHandleByIndex_v2",
    "nvmlDeviceGetHandleByPciBusId", "nvmlDeviceGetHandleByPciBusId_v2",
    "nvmlDeviceGetIndex", "nvmlDeviceGetName", "nvmlDeviceGetUUID",
    "nvmlDeviceGetPciInfo", "nvmlDeviceGetPciInfo_v2",
    "nvmlDeviceGetPciInfo_v3", "nvmlDeviceGetPciInfoExt",
    "nvmlDeviceGetMemoryInfo", "nvmlDeviceGetMemoryInfo_v2",
    "nvmlDeviceGetCudaComputeCapability",
    "nvmlDeviceGetCurrPcieLinkGeneration", "nvmlDeviceGetCurrPcieLinkWidth",
    "nvmlDeviceGetPcieLinkMaxSpeed", "nvmlDeviceGetPlatformInfo",
    "nvmlDeviceGetFieldValues", "nvmlDeviceGetMemoryErrorCounter",
    "nvmlDeviceGetGpuFabricInfoV", "nvmlDeviceGetNvLinkState",
    "nvmlDeviceGetNvLinkCapability", "nvmlDeviceGetNvLinkRemoteDeviceType",
    "nvmlDeviceGetNvLinkRemotePciInfo", "nvmlDeviceGetNvLinkRemotePciInfo_v2",
}
PINNED = re.compile(r"^nvml[A-Za-z0-9_]*$")


def symbols(path=REAL):
    out = subprocess.run(["nm", "-D", "--defined-only", path],
                         check=True, capture_output=True, text=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] == "T" and PINNED.match(parts[2]):
            names.append(parts[2])
    return sorted(set(names) - OVERRIDES)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    names = symbols()
    with open(f"{out}/nvml_forwarders.S", "w") as f:
        f.write("/* generated by gen_nvml_forwarders.py -- do not edit */\n\t.text\n")
        for n in names:
            f.write(
                f"\t.globl {n}\n\t.type {n}, @function\n{n}:\n"
                f"\tmovq nvml_fwd_{n}@GOTPCREL(%rip), %rax\n\tmovq (%rax), %rax\n"
                f"\ttestq %rax, %rax\n\tje 1f\n\tjmp *%rax\n"
                f"1:\tmovl $3, %eax\n\tret\n"      # NVML_ERROR_NOT_SUPPORTED
                f"\t.size {n}, .-{n}\n")
    with open(f"{out}/nvml_forwarders.c", "w") as f:
        f.write("/* generated by gen_nvml_forwarders.py -- do not edit */\n"
                "#define _GNU_SOURCE\n#include <dlfcn.h>\n#include <stdio.h>\n"
                "#include <stdlib.h>\nvoid *nvml_fwd_real_handle;\n")
        for n in names:
            f.write(f"void *nvml_fwd_{n};\n")
        f.write("\n__attribute__((constructor)) static void nvml_fwd_init(void) {\n"
                "    const char *p = getenv(\"NVML_REAL_LIB\");\n"
                f"    nvml_fwd_real_handle = dlopen(p ? p : \"{REAL}\", RTLD_NOW | RTLD_LOCAL);\n"
                "    if (!nvml_fwd_real_handle) { fprintf(stderr, \"nvml: cannot load real "
                "NVML: %s\\n\", dlerror()); return; }\n")
        for n in names:
            f.write(f"    nvml_fwd_{n} = dlsym(nvml_fwd_real_handle, \"{n}\");\n")
        f.write("}\n")
    print(f"{len(names)} NVML forwards + {len(OVERRIDES)} overrides")


if __name__ == "__main__":
    main()
