#!/usr/bin/env python3
"""Emit b300_spec.h from specs/b300_8x8.json -- D1 is the only source of identity.

Every shim in this directory includes the generated header, so no C file carries a
literal for the device name, HBM size, SM count or topology size.  A field D1 marks
UNVERIFIED does not reach an assertion; the header still carries it so the shims
cannot silently diverge from the spec, but the consumer must check the source.

    python3 shim/gen_spec.py <build-dir>
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
SPEC = os.path.join(REPO, "specs", "b300_8x8.json")


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    with open(SPEC) as f:
        s = json.load(f)
    m = s["models"]["b300_sxm"]
    n_nodes = len(s["nodes"])
    n_dev = max(len(n["devices"]) for n in s["nodes"]) if n_nodes else 0
    cc = m["compute_capability"]
    lines = [
        "/* generated by gen_spec.py from specs/b300_8x8.json -- do not edit */",
        "#ifndef B300_SPEC_H",
        "#define B300_SPEC_H",
        f'#define B300_NAME "{m["name"]}"',
        f"#define B300_NVDEV {n_dev}",
        f"#define B300_NODES {n_nodes}",
        f"#define B300_TOTAL_MEM_BYTES ({m['mem_bytes']}ull)",
        f"#define B300_SM_COUNT {m['sm_count']}",
        f"#define B300_CC_MAJOR {cc[0]}",
        f"#define B300_CC_MINOR {cc[1]}",
        f"#define B300_MEM_BW_GBPS {m['mem_bw_gbs']}",
        f"#define B300_NVLINK_GBPS {m['nvlink_bw_gbps']}",
        f"#define B300_PCIE_GEN {m['pcie_gen']}",
        f"#define B300_PCIE_WIDTH {m['pcie_width']}",
        f"#define B300_TDP_W {m['tdp_w']}",
        "/* virtual PCI bus ids live at 0x0b + device, one node per process */",
        "#define B300_PCI_BUS_BASE 0x0b",
        "#endif",
    ]
    with open(os.path.join(out, "b300_spec.h"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote b300_spec.h from {SPEC}: name={m['name']} devs={n_dev} nodes={n_nodes}")


if __name__ == "__main__":
    main()
