#!/usr/bin/env python3
"""gpu-sim-8g6: generate the per-member probe plugin source. CPU-only.

Reads the recovered member table (names, offsets, cast types) and emits a
plugin where EVERY function member has a DISTINCT stub that appends its own
(name, offset) marker to $U2O_MARKER and returns 0. If the loader calls
members in sequence, the marker file is the call trace; if a calling-
convention mismatch faults, the fault address maps to a member via nm/DWARF
(the stubs are distinct symbols, -g build).

Usage: python3 gen_probe.py --out probe_v11_markers.c
"""
import argparse
from pathlib import Path

# (member, offset, cast-to-assign) from experiments/gpu-sim-465.1/plugin_v11.c
MEMBERS = [
    ("init", 8, "int(*)(int)"),
    ("devices", 16, "int(*)(void)"),
    ("getProperties", 24, "int(*)(void*,void*)"),
    ("listen", 32, "int(*)(void*,void*)"),
    ("connect", 40, "int(*)(void*,void*,void*)"),
    ("accept", 48, "int(*)(void*,void*,void*)"),
    ("regMr", 56, "int(*)(void*)"),
    ("regMrDmaBuf", 64, "int(*)(void*)"),
    ("deregMr", 72, "int(*)(void*)"),
    ("isend", 80, "int(*)(int,void*,int,void*)"),
    ("irecv", 88, "int(*)(int,void*,int,void*)"),
    ("iflush", 96, "int(*)(int,void*,int,void*)"),
    ("test", 104, "int(*)(void*)"),
    ("closeSend", 112, "int(*)(void*)"),
    ("closeRecv", 120, "int(*)(void*)"),
    ("closeListen", 128, "int(*)(void*)"),
    ("getDeviceMr", 136, "int(*)(void*)"),
    ("irecvConsumed", 144, "int(*)(void*)"),
    ("makeVDevice", 152, "int(*)(void*)"),
    ("finalize", 160, "int(*)(void)"),
    ("setNetAttr", 168, "int(*)(void*,void*)"),
]
assert [o for _, o, _ in MEMBERS] == list(range(8, 176, 8)), "offsets must step 8"
assert len(MEMBERS) == 21


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    L = []
    L.append("/* gpu-sim-8g6 probe: per-member distinguishable stubs over the")
    L.append(" * recovered ncclNet_v11_t layout (176B, DWARF byte_size). Generated by")
    L.append(" * gen_probe.py -- do not hand-edit; edit the table there. */")
    L.append("#include <stdint.h>")
    L.append("#include <stddef.h>")
    L.append("#include <stdio.h>")
    L.append("#include <stdlib.h>")
    L.append("")
    L.append("typedef struct ncclNet_v11_t ncclNet_v11_t;")
    L.append("struct ncclNet_v11_t {")
    L.append("    const char       *name;")
    for name, off, cast in MEMBERS:
        ret, fargs = cast.split("(*)")
        L.append(f"    {ret}(*{name}){fargs}; /* +{off} */")
    L.append("};")
    L.append('_Static_assert(sizeof(ncclNet_v11_t) == 176, "layout must match DWARF");')
    L.append("")
    L.append("static void mark(const char *member, int off) {")
    L.append("    const char *p = getenv(\"U2O_MARKER\");")
    L.append("    if (!p) return;")
    L.append("    FILE *f = fopen(p, \"a\");")
    L.append("    if (!f) return;")
    L.append('    fprintf(f, "{\\"member\\": \\"%s\\", \\"off\\": %d}\\n", member, off);')
    L.append("    fclose(f);")
    L.append("}")
    L.append("__attribute__((constructor)) static void probe_loaded(void) { mark(\"LOADED\", -1); }")
    L.append("")
    for name, off, cast in MEMBERS:
        L.append(f"static int stub_{name}(void) {{ mark(\"{name}\", {off}); return 0; }}")
    L.append("")
    L.append("static ncclNet_v11_t g_plugin = {")
    L.append('    .name = "u2o-probe-net",')
    for name, off, cast in MEMBERS:
        L.append(f"    .{name} = ({cast})stub_{name},")
    L.append("};")
    L.append("")
    L.append("#define ENTRY(VER) __attribute__((visibility(\"default\"))) ncclNet_v11_t* ncclNetPlugin##VER(void* logFunction) { (void)logFunction; return &g_plugin; }")
    L.append("ENTRY(_v6) ENTRY(_v7) ENTRY(_v8) ENTRY(_v9) ENTRY(_v10) ENTRY(_v11)")
    L.append("")
    Path(args.out).write_text("\n".join(L))
    print(f"members={len(MEMBERS)} -> {args.out}")


if __name__ == "__main__":
    main()
