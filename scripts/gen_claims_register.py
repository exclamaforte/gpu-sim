#!/usr/bin/env python3
"""Generate and verify the CLAIMS REGISTER -- one row per load-bearing claim (gpu-sim-reg).

Every correction this lab made came from asking "what is the MARGIN on that claim", not from
re-reading the answer. The answers themselves held; the confidence language around them did not.
This script turns that lesson into an artifact: a table in docs/training-parallelism-sim.md
whose numbers are READ FROM docs/model_facts.json, so the register cannot drift from the model,
and whose wording states the confidence class explicitly:

  VERDICT       margin >= 2% against the best different shape at every plausible efficiency
  TIE           the config is right but the margin is < 2% -- do not present it as a ranking
  BOUNDED       a range is measured (e.g. absolute durations), the point value is not
  STRUCTURAL    a property that holds by construction (e.g. a knob that cannot affect time)
  VALIDATED     checked against harness output, with the residual named
  UNVALIDATED   no path on this hardware; stated so a reader knows what to discount

`--check` regenerates and compares against what the doc contains, so a stale register fails the
gate instead of quietly describing a model that no longer exists.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "training-parallelism-sim.md"
FACTS = ROOT / "docs" / "model_facts.json"
BEGIN = "<!-- CLAIMS-REGISTER:BEGIN (generated by scripts/gen_claims_register.py) -->"
END = "<!-- CLAIMS-REGISTER:END -->"


def _row(claim, status, evidence, guard):
    return f"| {claim} | **{status}** | {evidence} | {guard} |"


def render(facts):
    frag = facts["fragility_map"]["grid"]

    def cell(n, seq, tag="implied"):
        c = frag[f"N{n}_seq{seq}"][tag]
        return c["margin_pct"], c["config"]

    m8, _ = cell(8, 8192)
    m8b, _ = cell(8, 8192, "typical")
    m8_16k, _ = cell(8, 16384)
    m8_32k, _ = cell(8, 32768)
    m16_8k_typ, _ = cell(16, 8192, "typical")
    m16_16k, _ = cell(16, 16384)
    m16_16k_typ, _ = cell(16, 16384, "typical")
    m16_32k, _ = cell(16, 32768, "measured")
    m32_worst = min(frag[f"N32_seq{s}"][t]["margin_pct"]
                    for s in (8192, 16384, 32768) for t in ("implied", "measured", "typical"))
    mfu = facts["mfu_sensitivity"]
    knob = facts["act_factor_knob"]
    cross = facts["cp_crossover"]
    head = facts["headroom_sensitivity"]["grid"]["N16_seq32768"]
    apc = facts["alpha_piece_charging"]

    rows = [
        _row("N=8 winner (tp=4 pp=1 cp=2 dp=1 z0), seq 8192", "VERDICT",
             f"{facts['rows']['N8']['winner']['step_ms']} ms; margin {m8}% at the implied MFU, "
             f"{m8b:.2f}% at 40%",
             "tests/test_fragility_map.py"),
        _row("Same config at seq 16384 / 32768", "TIE",
             f"margin only {m8_16k:.2f}% / {m8_32k:.2f}% -- the config is right, the ranking is "
             f"not decisive",
             "tests/test_fragility_map.py"),
        _row("N=16 winner (tp=1 pp=4 cp=1 dp=4 z2), seq 8192", "TIE",
             f"{m16_8k_typ:.2f}% at 40% MFU; flips below MFU {facts['mfu_margin_sweep']['N16_crossover_mfu']}",
             "tests/test_mfu_sensitivity.py"),
        _row("N=16 at seq 16384", "TIE",
             f"three-way tangle: winner moves to (1,2,1,8) at 40%, margins "
             f"{m16_16k:.2f}% / {m16_16k_typ:.2f}%",
             "tests/test_fragility_map.py"),
        _row("N=16 at seq 32768 (hard-fit memory)", "TIE",
             f"{m16_32k:.2f}% margin and 94% of HBM; 10% headroom swaps it to "
             f"({', '.join(str(x) for x in head['hr0.10']['config'])}) at "
             f"{head['hr0.10']['mem_gb']} GB (+1.9%)",
             "tests/test_memory_headroom.py"),
        _row("N=32 winner (tp=1 pp=4 cp=1 dp=8 z2)", "VERDICT",
             f"margin {m32_worst:.2f}% at worst over every seq and efficiency tested",
             "tests/test_fragility_map.py"),
        _row("Absolute step durations", "BOUNDED",
             f"model implies {mfu['implied_0.765']['implied_mfu']:.3f} MFU; a real GPU reached "
             f"{mfu['measured_5090']['mfu']:.3f}, so absolutes carry "
             f"{mfu['ratio_at_measured']}-{mfu['ratio_at_typical']}x",
             "tests/test_mfu_sensitivity.py"),
        _row("act_factor (2.3) fitted constant", "STRUCTURAL",
             f"memory-only: 5x band changes no step time; ranking bends only at "
             f"{knob['bend_point']['N8']} (N=8) / {knob['bend_point']['N16']} (N=16,32)",
             "tests/test_act_factor_knob.py"),
        _row("S_best = 8192", "VALIDATED",
             f"CP crossover is seq {cross['implied_seq']} ({cross['measured_seq']} measured), so "
             f"8192 is the first conventional length above it, "
             f"+{cross['advantage_at_8192_implied_pct']:.2f}%",
             "tests/test_cp_crossover.py"),
        _row("Alpha piece-charging granularity", "BOUNDED",
             f"+{round(100 * (apc['8']['step_ms'] / apc['1']['step_ms'] - 1), 1)}% at P=8, winner unmoved",
             "docs section 0 (alpha piece charging)"),
        _row("DP byte counts / payload", "VALIDATED",
             "reconciles against harness traces to 2.5%, residual = param_count() pos/LN exclusion",
             "tests/test_reconcile_bytes.py"),
        _row("TP byte counts / payload", "VALIDATED",
             "message count matches the plan exactly; payload B*seq*d is tp-independent",
             "tests/test_parallelism_counts.py"),
        _row("CP byte accounting", "UNVALIDATED",
             "harness moves 109.8 MB/step (AG+RS) where the model prices 21.0 MB of ring p2p; "
             "different algorithms, not reconciled by construction",
             "tests/test_cp_payload_structure.py"),
        _row("Absolute communication durations", "UNVALIDATED",
             "rest on the model's ring alpha/bw; needs a 2-4 GPU NVLink run, unavailable on one GPU",
             "no test possible here"),
    ]
    out = [BEGIN, "", "| claim | status | evidence | guard |", "|---|---|---|---|"]
    out += rows
    out += ["", END]
    return "\n".join(out)


def main() -> int:
    facts = json.loads(FACTS.read_text())
    block = render(facts)
    text = DOC.read_text()

    if "--check" in sys.argv:
        if BEGIN not in text:
            print("claims register missing from the doc")
            return 1
        current = text[text.index(BEGIN):text.index(END) + len(END)]
        if current.strip() != block.strip():
            print("STALE claims register: docs/training-parallelism-sim.md does not match "
                  "docs/model_facts.json")
            old = {l.split("|")[1].strip() for l in current.splitlines() if l.startswith("|")}
            new = {l.split("|")[1].strip() for l in block.splitlines() if l.startswith("|")}
            for line in sorted(old ^ new):
                print(f"  differs: {line[:90]}")
            print("  run: python3 scripts/gen_claims_register.py")
            return 1
        print(f"claims register current ({block.count('| **')} claims)")
        return 0

    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text = text.rstrip() + "\n\n## Claims register (generated)\n\n" + block + "\n"
    DOC.write_text(text)
    print(f"wrote {block.count('| **')} claims into docs/training-parallelism-sim.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
