#!/usr/bin/env python3
"""Best parallelism at scale-out: 10, 100 and 1000 nodes of 8x H100 (gpu-sim-scaleout).

Builds the fabric in memory (intra-node NVLink full mesh, inter-node rail ring per GPU at one NDR NIC per
GPU = 50 GB/s, 5 us) and asks the production model which decomposition wins for several model sizes.

Every caveat this project has established still applies and is printed with the table:
  * batch = 1 per rank (the DP sync is per STEP, payload comm is per TOKEN, so batch=1 flatters DP-avoiding
    configs -- real training at scale uses far larger batches and will shift these answers toward DP);
  * the CP term is quoted under BOTH conventions, because PyTorch's default rotate method (all_gather)
    moves 1.99x what the model's ring pricing assumes;
  * absolute durations are bounded to 1.28-1.69x by measurement, not predictions.

Usage: python3 scripts/scaleout_answers.py [--json] [--nodes 10,100,1000]
       [--recompute 0.0..1.0] [--models llama3-8b,llama3-70b,llama3-405b]
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from epic_cluster import parallelism_search as ps  # noqa: E402

PEAK = 989e12          # H100 SXM bf16 dense peak, as used everywhere else in this repo
HBM_GB = 80.0

MODELS = {
    "llama3-8b": {"n_layers": 32, "d_model": 4096, "n_heads": 32, "n_kv_heads": 8, "head_dim": 128,
                  "d_ff": 14336, "vocab": 128256, "seq": 8192},
    "llama3-70b": {"n_layers": 80, "d_model": 8192, "n_heads": 64, "n_kv_heads": 8, "head_dim": 128,
                   "d_ff": 28672, "vocab": 128256, "seq": 8192},
    "llama3-405b": {"n_layers": 126, "d_model": 16384, "n_heads": 128, "n_kv_heads": 8, "head_dim": 128,
                    "d_ff": 53248, "vocab": 128256, "seq": 8192},
}
CONVENTIONS = {"ring all_to_all": 1.0, "default all_gather": 1.9922}


def build_spec(nodes: int) -> dict:
    """8x H100 per node: NVLink 4 full mesh inside, one 400 Gb/s NIC per GPU across nodes.

    Cross-node is a per-rail RING (GPU g of node i links to GPU g of node i+1). Rail-optimised fabrics are
    switches, not rings, but a ring is the topology NCCL actually walks for a cross-node ring all-reduce,
    and the model prices a ring; using a full mesh here would make every cross-node hop one link and
    flatter wide collectives.
    """
    devs = [{"id": g, "model": "h100_sxm"} for g in range(8)]
    spec = {
        "version": 1,
        "sources": {"spec": "generated by scripts/scaleout_answers.py; NVLink 4 intra-node, NDR IB per GPU"},
        "models": {"h100_sxm": {"sm_count": 132, "clock_mhz": 1830, "mem_bytes": 85899345920,
                                "mem_bw_gbs": 3350, "arch": "sm_90"}},
        "nodes": [{"name": f"node{i}", "devices": [dict(d) for d in devs]} for i in range(nodes)],
        "links": [],
        "ranks": [],
    }
    for i in range(nodes):
        for a in range(8):
            for b in range(a + 1, 8):
                spec["links"].append({"a": {"node": f"node{i}", "device": a},
                                      "b": {"node": f"node{i}", "device": b},
                                      "kind": "nvlink", "bw_gbps": 900.0, "bw_is_bidirectional": True,
                                      "latency_us": 1.0, "mtu": 4096, "loss_ppm": 0, "jitter_us": 0,
                                      "shared_group": None})
    if nodes > 1:
        for i in range(nodes):
            j = (i + 1) % nodes
            for g in range(8):
                spec["links"].append({"a": {"node": f"node{i}", "device": g},
                                      "b": {"node": f"node{j}", "device": g},
                                      "kind": "ib", "bw_gbps": 50.0, "bw_is_bidirectional": False,
                                      "latency_us": 5.0, "mtu": 4096, "loss_ppm": 0, "jitter_us": 0,
                                      "shared_group": None})
    for i in range(nodes):
        for g in range(8):
            spec["ranks"].append({"node": f"node{i}", "device": g})
    return spec


MAX_TP = 8          # TP needs NVLink-class all-to-all per layer; one node is the practical domain
                    # (the raw search will happily return tp=16 across nodes -- that is a model artefact)


def answer(spec: dict, model: dict, n: int, cp_scale: float, batch: int = 1,
            recompute: float = 0.0) -> dict | None:
    hw = {"peak_flops": PEAK, "mem_gb": HBM_GB, "spec": spec, "term_scale": {"cp": cp_scale},
          "batch": batch, "recompute": recompute}
    _, feas = ps.search(n, hw, model)
    # Two constraints the raw search does not apply, both of which remove configs no one would run:
    #   tp <= 8   : beyond a node, TP's per-layer all-to-all crosses the NIC
    #   pp <= layers : a stage must own at least one layer
    feas = [c for c in feas if c.tp <= MAX_TP and c.pp <= model["n_layers"]]
    if not feas:
        return None
    best = feas[0]
    alt = next((c for c in feas if (c.tp, c.pp, c.cp, c.dp) != (best.tp, best.pp, best.cp, best.dp)), None)
    return {
        "config": f"tp={best.tp} pp={best.pp} cp={best.cp} dp={best.dp} zero={best.zero}",
        "tp": best.tp, "pp": best.pp, "cp": best.cp, "dp": best.dp, "zero": best.zero,
        "step_s": round(best.step_sum, 3),
        "margin_pct": round(100 * (alt.step_sum / best.step_sum - 1), 2) if alt else None,
        "mem_gb": round(best.memory_gb, 1),
        "n_feasible": len(feas),
        "constrained": True,
    }


def main() -> int:
    nodes_list = [10, 100, 1000]
    if "--nodes" in sys.argv:
        nodes_list = [int(x) for x in sys.argv[sys.argv.index("--nodes") + 1].split(",")]
    # gpu-sim-hz3u: sweep the activation-recompute knob (float 0.0..1.0, default 0.0,
    # so every published number is bit-identical; 1.0 = full checkpointing, measured
    # 1.25x compute and 0.45x retained activations -- see experiments/gpu-sim-recompute/).
    recompute = 0.0
    if "--recompute" in sys.argv:
        recompute = float(sys.argv[sys.argv.index("--recompute") + 1])
        assert 0.0 <= recompute <= 1.0, f"recompute must be in [0, 1], got {recompute}"
    want = None
    if "--models" in sys.argv:
        want = set(sys.argv[sys.argv.index("--models") + 1].split(","))
    models = {k: v for k, v in MODELS.items() if want is None or k in want}
    out = {}
    batches = [1, 8]          # 1 = every published number; 8 = a realistic per-rank micro-batch
    for nodes in nodes_list:
        n = nodes * 8
        spec = build_spec(nodes)
        out[f"{nodes}x8"] = {"n_gpus": n, "models": {}}
        for name, model in models.items():
            out[f"{nodes}x8"]["models"][name] = {}
            for batch in batches:
                for cname, scale in CONVENTIONS.items():
                    key = cname if batch == 1 else f"{cname}, batch={batch}"
                    out[f"{nodes}x8"]["models"][name][key] = answer(spec, model, n, scale,
                                                                      batch, recompute)
    if "--json" in sys.argv:
        print(json.dumps(out, indent=2))
        return 0
    # markdown
    print("| fabric | model | CP convention / batch | best config | step (s) | margin | mem/GPU |")
    print("|---|---|---|---|---|---|---|")
    for fabric, blob in out.items():
        for mname, rows in blob["models"].items():
            for cname, r in rows.items():
                if r is None:
                    print(f"| {fabric} | {mname} | {cname} | INFEASIBLE | - | - | - |")
                else:
                    marg = f"{r['margin_pct']:.2f}%" if r["margin_pct"] is not None else "n/a"
                    print(f"| {fabric} | {mname} | {cname} | {r['config']} | {r['step_s']:.3f} | "
                          f"{marg} | {r['mem_gb']} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
