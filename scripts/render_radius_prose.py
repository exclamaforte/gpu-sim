#!/usr/bin/env python3
"""Render the numeric radius intervals from scripts/sensitivity_radius.py into the doc.

Emits a marker-delimited block sourced from docs/model_facts.json -> sensitivity_radius, so the
intervals cannot drift from the model. None flips render as 'unbounded' (no sweep floors/sentinels).

Usage:
  python3 scripts/render_radius_prose.py           # print the block
  python3 scripts/render_radius_prose.py --write   # write it into the doc between markers
  python3 scripts/render_radius_prose.py --check   # fail if the committed block differs
"""
from __future__ import annotations
import json, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "training-parallelism-sim.md"
FACTS = ROOT / "docs" / "model_facts.json"
BEGIN = "<!-- RADIUS-PROSE:BEGIN (generated by scripts/render_radius_prose.py) -->"
END = "<!-- RADIUS-PROSE:END -->"


def _fmt(v):
    if v is None:
        return "unbounded"
    return f"{v}"


def render(facts):
    sr = facts["sensitivity_radius"]
    lines = [BEGIN]
    for key in sorted(sr):
        row = sr[key]
        cp_lo = _fmt(row.get("flip_cp_down"))
        cp_hi = _fmt(row.get("flip_cp_up"))
        pp_lo = _fmt(row.get("flip_pp_down"))
        pp_hi = _fmt(row.get("flip_pp_up"))
        lines.append(f"{key}: CP [{cp_lo}, {cp_hi}], PP [{pp_lo}, {pp_hi}]")
    lines.append(END)
    return "\n".join(lines) + "\n"


def _read_doc():
    return DOC.read_text()


def _find_block(text):
    i = text.find(BEGIN)
    j = text.find(END)
    if i == -1 or j == -1 or j < i:
        return None, i, j
    # include the END marker line
    end_line = text.find("\n", j)
    if end_line == -1:
        end_line = len(text)
    else:
        end_line += 1
    return text[i:end_line], i, end_line


def main() -> int:
    args = sys.argv[1:]
    facts = json.loads(FACTS.read_text())
    block = render(facts)
    text = _read_doc()
    if "--check" in args:
        existing, i, j = _find_block(text)
        if existing is None:
            print("RADIUS-PROSE: markers missing or malformed")
            return 1
        if existing != block:
            print("RADIUS-PROSE: committed block differs from regeneration")
            print("--- committed ---")
            print(existing)
            print("--- regenerated ---")
            print(block)
            return 1
        print("RADIUS-PROSE: OK")
        return 0
    if "--write" in args:
        existing, i, j = _find_block(text)
        if existing is None:
            # append at end
            text = text.rstrip("\n") + "\n\n" + block
        else:
            text = text[:i] + block + text[j:]
        DOC.write_text(text)
        print(f"wrote radius-prose block to {DOC}")
        return 0
    sys.stdout.write(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
