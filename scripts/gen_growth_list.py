#!/usr/bin/env python3
"""Generate and verify the 6kp cu* growth list.

Source A: nm -D --undefined-only libnccl.so, filtered to cuda*/cu* (what NCCL needs).
Source B: nm -D --defined-only libfakegpu.so, filtered to cuda*/cu* (what we provide).
Growth list = A minus B (symbols NCCL needs but shim doesn't provide).

Usage:
  python3 scripts/gen_growth_list.py --check   # verify committed file matches
  python3 scripts/gen_growth_list.py --gen     # regenerate committed file
"""
import subprocess, sys, os, re

NCCL = "/tmp/ncclsrc/nccl-2.32.3-1/build/lib/libnccl.so.2"
SHIM = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "libfakegpu.so")
GROWTH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                      "experiments", "gpu-sim-6kp", "growth_list.txt")

def nm_undef(path):
    out = subprocess.check_output(["nm", "-D", "--undefined-only", path],
                                 stderr=subprocess.DEVNULL, text=True)
    syms = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[-1]:
            sym = parts[-1].split("@")[0]
            if re.match(r'^(cuda|cu[A-Z])', sym):
                syms.add(sym)
    return syms

def nm_defined(path):
    out = subprocess.check_output(["nm", "-D", "--defined-only", path],
                                 stderr=subprocess.DEVNULL, text=True)
    syms = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[-1]:
            sym = parts[-1].split("@")[0]
            if re.match(r'^(cuda|cu[A-Z])', sym):
                syms.add(sym)
    return syms

def main():
    a = nm_undef(NCCL)
    b = nm_defined(SHIM)
    growth = sorted(a - b)

    if "--gen" in sys.argv:
        with open(GROWTH, "w") as f:
            f.write("# gpu-sim-6kp growth list (auto-generated by scripts/gen_growth_list.py)\n")
            f.write("# Source A: nm -D --undefined-only libnccl.so (cuda*/cu* symbols NCCL needs)\n")
            f.write("# Source B: nm -D --defined-only libfakegpu.so (cuda*/cu* symbols shim provides)\n")
            f.write("# Growth list = A - B (symbols NCCL needs but shim does not provide)\n")
            f.write("# All entries are link-time undefined (nm-visible). dlsym/versioned-boundary\n")
            f.write("# paths would not appear here; no runtime witness this increment (recorded gap).\n")
            f.write("#\n")
            for sym in growth:
                f.write(sym + "\n")
        print("Generated %d entries -> %s" % (len(growth), GROWTH))
        return 0

    if "--check" in sys.argv:
        # Read committed file, extract symbol lines (skip comments/blanks)
        committed = set()
        for line in open(GROWTH):
            line = line.strip()
            if line and not line.startswith("#"):
                committed.add(line)
        if committed == set(growth):
            print("PASS: growth list matches (A-B) exactly (%d entries)" % len(growth))
            return 0
        else:
            missing = set(growth) - committed
            extra = committed - set(growth)
            if missing:
                print("FAIL: missing entries (%d): %s" % (len(missing), sorted(missing)))
            if extra:
                print("FAIL: extra entries (%d): %s" % (len(extra), sorted(extra)))
            return 1

    print("Usage: --check or --gen")
    return 2

if __name__ == "__main__":
    sys.exit(main())
